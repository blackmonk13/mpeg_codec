/// A package for handling MP4 metadata and related operations.
///
/// This package provides various modules for working with MP4 metadata, such as
/// handling exceptions, managing genres, processing metadata, handling MP4 files,
/// and more.
///
/// The package is organized into the following modules:
///
/// - `src/exceptions.dart`: Contains custom exception classes for handling errors
///   related to MP4 metadata operations.
///
/// - `src/genres.dart`: Provides functions for working with genres, such as
///   converting genres to a formatted string for MP4 metadata.
///
/// - `src/id3.dart`: Contains utility functions and classes for working with
///   ID3 encoded files, such as reading and writing ID3 data.
///
/// - `src/handler.dart`: Contains classes and functions for handling MP4 metadata
///   operations, such as reading and writing metadata to MP4 files.
///
/// - `src/metadata.dart`: Provides classes and functions for working with MP4
///   metadata, such as accessing and modifying metadata fields.
///
/// - `src/mp4.dart`: Contains utility functions and classes for working with MP4
///   files, such as reading and writing MP4 data.
library;

export 'src/exceptions.dart';
export 'src/genres.dart';
export 'src/handler.dart';
export 'src/id3.dart';
export 'src/metadata.dart';
export 'src/mp4.dart';
